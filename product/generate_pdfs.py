#!/usr/bin/env python3
"""
Regenerates the three downloadable PDFs (recipe book, tech cards,
checklists) from the content data below. Run: python3 generate_pdfs.py
Output goes to product/pdf/ — the files served by
src/app/api/downloads/[file]/route.ts.

Uses DejaVu Sans (bundled on most Linux systems, or install via
`apt-get install fonts-dejavu`) for Cyrillic glyph support — the
built-in reportlab fonts (Helvetica etc) do not cover Cyrillic.
"""
import os
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak, HRFlowable
)
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

FONT_DIR = "/usr/share/fonts/truetype/dejavu"
pdfmetrics.registerFont(TTFont("DejaVu", f"{FONT_DIR}/DejaVuSans.ttf"))
pdfmetrics.registerFont(TTFont("DejaVu-Bold", f"{FONT_DIR}/DejaVuSans-Bold.ttf"))

OUT_DIR = os.path.join(os.path.dirname(__file__), "pdf")
os.makedirs(OUT_DIR, exist_ok=True)

BERRY = colors.HexColor("#A52C50")
CHOCO = colors.HexColor("#2B1B24")
SOFT = colors.HexColor("#6B4F5C")
LINE = colors.HexColor("#EAD9CF")

styles = getSampleStyleSheet()
styles.add(ParagraphStyle("TitleRU", fontName="DejaVu-Bold", fontSize=24, textColor=CHOCO, spaceAfter=6))
styles.add(ParagraphStyle("SubtitleRU", fontName="DejaVu", fontSize=11, textColor=SOFT, spaceAfter=16))
styles.add(ParagraphStyle("H1RU", fontName="DejaVu-Bold", fontSize=16, textColor=BERRY, spaceBefore=18, spaceAfter=8))
styles.add(ParagraphStyle("H2RU", fontName="DejaVu-Bold", fontSize=12.5, textColor=CHOCO, spaceBefore=10, spaceAfter=4))
styles.add(ParagraphStyle("BodyRU", fontName="DejaVu", fontSize=10, textColor=CHOCO, leading=14))
styles.add(ParagraphStyle("MetaRU", fontName="DejaVu", fontSize=9, textColor=SOFT, leading=13))
styles.add(ParagraphStyle("TipRU", fontName="DejaVu", fontSize=9.5, textColor=BERRY, leading=13, leftIndent=8))


def brand_header(title, subtitle):
    return [
        Paragraph("Дом Десертов", ParagraphStyle("brand", fontName="DejaVu-Bold", fontSize=12, textColor=BERRY)),
        Spacer(1, 10),
        Paragraph(title, styles["TitleRU"]),
        Paragraph(subtitle, styles["SubtitleRU"]),
        HRFlowable(width="100%", color=LINE, thickness=1),
        Spacer(1, 12),
    ]


